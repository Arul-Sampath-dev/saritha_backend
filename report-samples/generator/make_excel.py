OUT = sys.argv[1]
INR = '[>=10000000]"₹"##\\,##\\,##\\,##0.00;[>=100000]"₹"##\\,##\\,##0.00;"₹"##,##0.00'
INR_NEG = INR  # amounts here are never negative except net, handled by the same format with a minus
DATE = "dd-mmm-yyyy"
DATETIME = "dd-mmm-yyyy h:mm AM/PM"
PERIOD = f"{D.FROM:%d %b %Y} – {D.TO:%d %b %Y}"

INK = "17171C"; SLATE = "75758A"; GREEN = "003C33"
HEAD_FILL = PatternFill("solid", fgColor="F4F4F6")
TOTAL_FILL = PatternFill("solid", fgColor="EDFCE9")
BAND_FILL = PatternFill("solid", fgColor=GREEN)
thin = Side(style="thin", color="E5E7EB")
BOTTOM = Border(bottom=thin)

wb = Workbook()


def sheet(title, heading, first=False):
    ws = wb.active if first else wb.create_sheet()
    ws.title = title
    ws.sheet_view.showGridLines = False
    ws["A1"] = heading
    ws["A1"].font = Font(name="Calibri", size=14, bold=True, color=INK)
    ws["A2"] = f"{D.BRANCH['name']} · {PERIOD}"
    ws["A2"].font = Font(size=10, color=SLATE)
    return ws


def table(ws, row, headers, rows, kinds, widths=None, totals=None, title=None):
    """headers + rows from `row`; kinds per column: text|int|money|date|datetime|pct. totals: list of column indexes to SUM."""
    if title:
        ws.cell(row=row, column=1, value=title).font = Font(bold=True, size=11, color=INK)
        row += 1
    for c, h in enumerate(headers, 1):
        cell = ws.cell(row=row, column=c, value=h)
        cell.font = Font(bold=True, color=INK, size=10)
        cell.fill = HEAD_FILL
        cell.border = BOTTOM
        cell.alignment = Alignment(horizontal="right" if kinds[c - 1] in ("int", "money", "pct") else "left", vertical="center")
    head_row = row
    if not rows:
        ws.cell(row=row + 1, column=1, value="None in this period").font = Font(italic=True, color=SLATE)
        return row + 3, head_row
    for r in rows:
        row += 1
        for c, v in enumerate(r, 1):
            cell = ws.cell(row=row, column=c, value=v)
            k = kinds[c - 1]
            if k == "money":
                cell.number_format = INR
            elif k == "date":
                cell.number_format = DATE
            elif k == "datetime":
                cell.number_format = DATETIME
            elif k == "pct":
                cell.number_format = '0.0"%"'
            elif k == "int":
                cell.number_format = "#,##0"
            cell.alignment = Alignment(horizontal="right" if k in ("int", "money", "pct") else "left", vertical="top", wrap_text=k == "wrap")
            cell.border = BOTTOM
    if totals:
        row += 1
        ws.cell(row=row, column=1, value="Total").font = Font(bold=True)
        for c in range(1, len(headers) + 1):
            ws.cell(row=row, column=c).fill = TOTAL_FILL
        for c in totals:
            L = get_column_letter(c)
            cell = ws.cell(row=row, column=c, value=f"=SUM({L}{head_row + 1}:{L}{row - 1})")
            cell.font = Font(bold=True)
            cell.number_format = INR if kinds[c - 1] == "money" else "#,##0"
            cell.alignment = Alignment(horizontal="right")
    if widths:
        for c, w in enumerate(widths, 1):
            cur = ws.column_dimensions[get_column_letter(c)].width or 0
            ws.column_dimensions[get_column_letter(c)].width = max(cur, w)
    return row + 2, head_row


def freeze_filter(ws, head_row, ncols, last_row):
    ws.freeze_panes = ws.cell(row=head_row + 1, column=1)
    ws.auto_filter.ref = f"A{head_row}:{get_column_letter(ncols)}{last_row}"


